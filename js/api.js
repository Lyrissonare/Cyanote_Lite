/* Cyanote Lite API client — drop-in replacement for the REST client of the
   full Cyanote build. There is no server: content lives in two static JSON
   files (content/index.json + content/settings.json) generated by build.mjs,
   and the former /api/* endpoints are emulated in the browser with identical
   response shapes, so every page module runs unmodified. */

import { computeMeta, listArticles, getArticle, archivePosts } from './store.js';

let manifestPromise = null;
let settingsPromise = null;

const fetchJson = (url) =>
  fetch(url, { cache: 'no-cache' }).then(async (res) => {
    if (!res.ok) throw new Error(`加载 ${url} 失败 (${res.status})`);
    return res.json();
  });

export function getManifest() {
  if (!manifestPromise) {
    manifestPromise = fetchJson('content/index.json').catch((err) => {
      manifestPromise = null; // retry on next call (e.g. after a publish)
      throw err;
    });
  }
  return manifestPromise;
}

export function invalidateManifest() {
  manifestPromise = null;
}

export function getSettings() {
  if (!settingsPromise) {
    settingsPromise = fetchJson('content/settings.json').catch((err) => {
      settingsPromise = null;
      throw err;
    });
  }
  return settingsPromise;
}

function handleGet(path) {
  const [route, qs] = path.split('?');
  const query = new URLSearchParams(qs || '');

  if (route === '/api/meta') return getManifest().then((m) => computeMeta(m.posts));
  if (route === '/api/settings') return getSettings();
  if (route === '/api/archive') return getManifest().then((m) => archivePosts(m.posts));

  if (route === '/api/articles') {
    return getManifest().then((m) =>
      listArticles(m.posts, {
        category: query.get('category') || undefined,
        tag: query.get('tag') || undefined,
        q: query.get('q') || undefined,
        page: query.get('page') || undefined,
        pageSize: query.get('pageSize') || undefined,
        order: query.get('order') || undefined,
      })
    );
  }

  const bySlug = route.match(/^\/api\/articles\/([^/?]+)$/);
  if (bySlug) {
    return getManifest().then((m) => {
      const article = getArticle(m.posts, decodeURIComponent(bySlug[1]));
      if (!article) throw new Error('文章不存在');
      return article;
    });
  }

  throw new Error(`接口不存在：${route}`);
}

export async function api(path, opts = {}) {
  if ((opts.method || 'GET').toUpperCase() !== 'GET') {
    throw new Error('Cyanote Lite 是纯静态站点：请在本地编辑 Markdown 后重新构建');
  }
  return handleGet(path);
}

export const get = (p) => api(p);
